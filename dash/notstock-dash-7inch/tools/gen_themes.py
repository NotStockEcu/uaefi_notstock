def build_hill():
    img, d = canvas((0x1C, 0x1D, 0x1F))
    img = vignette(img, 0.35)
    d = ImageDraw.Draw(img)
    cx, cy = u(HILL_CX), u(HILL_CY)

    # bezel
    d.ellipse([cx - u(HILL_R + 12), cy - u(HILL_R + 12), cx + u(HILL_R + 12),
               cy + u(HILL_R + 12)], fill=(0x0C, 0x0C, 0x0D))
    d.ellipse([cx - u(HILL_R + 8), cy - u(HILL_R + 8), cx + u(HILL_R + 8),
               cy + u(HILL_R + 8)], fill=(0x3A, 0x3B, 0x3E))
    d.ellipse([cx - u(HILL_R + 3), cy - u(HILL_R + 3), cx + u(HILL_R + 3),
               cy + u(HILL_R + 3)], fill=(0x10, 0x10, 0x11))

    # face: yellow, red wedge past 7000
    def ang(rpm):
        return HILL_START + HILL_SWEEP * rpm / 8000

    d.ellipse([cx - u(HILL_R), cy - u(HILL_R), cx + u(HILL_R), cy + u(HILL_R)],
              fill=(0xFF, 0xD2, 0x1A))
    sector(d, cx, cy, 0, u(HILL_R), ang(7000), ang(8000) + 4,
           (0xE0, 0x2A, 0x2A))
    # dark centre
    d.ellipse([cx - u(64), cy - u(64), cx + u(64), cy + u(64)],
              fill=(0x16, 0x16, 0x17))

    blk = (0x12, 0x12, 0x12)
    for i in range(0, 33):
        rpm = i * 250
        a = ang(rpm)
        major = rpm % 1000 == 0
        half = rpm % 500 == 0
        col = (0xFF, 0xFF, 0xFF) if rpm >= 7000 else blk
        ln = 22 if major else (14 if half else 9)
        radial(d, cx, cy, u(HILL_R - 4), u(HILL_R - 4 - ln), a,
               u(5 if major else 2.4), col)
    fn = f_("BarlowCondensed-Bold.ttf", 44)
    for k in range(9):
        col = (0xFF, 0xFF, 0xFF) if k >= 7 else blk
        x, y = pt(cx, cy, u(HILL_R - 50), ang(k * 1000))
        text_c(d, x, y, str(k), fn, col)
    fx = f_("BarlowCondensed-SemiBold.ttf", 16)
    text_c(d, cx, cy - u(HILL_R - 88), "x1000 RPM", fx, blk)

    # tiles with an empty bargraph slot on the outer edge
    fl = f_("BarlowCondensed-SemiBold.ttf", 17)
    for (x, y, left), lab in zip(HILL_TILES, HILL_LABELS):
        d.rounded_rectangle([u(x), u(y), u(x + HILL_TILE_W), u(y + HILL_TILE_H)],
                            radius=u(6), fill=(0x26, 0x27, 0x29),
                            outline=(0x3A, 0x3B, 0x3E), width=u(2))
        bx = x + 10 if left else x + HILL_TILE_W - 34
        seg_h = (HILL_TILE_H - 24) / HILL_SEGS
        for s in range(HILL_SEGS):
            sy = y + 12 + s * seg_h
            d.rectangle([u(bx), u(sy + 1.5), u(bx + 24), u(sy + seg_h - 1.5)],
                        fill=(0x3A, 0x38, 0x2A))
        tx = x + 44 if left else x + 12
        d.text((u(tx), u(y + HILL_TILE_H - 30)), lab, font=fl,
               fill=(0xE8, 0xE8, 0xE8))

    img = finish(img)
    save_png("theme_hill", img)

    needle, piv = gen_dials.build_needle(HILL_NEEDLE_LEN, 12, 4, 26)
    hub = gen_dials.build_hub(HILL_HUB)

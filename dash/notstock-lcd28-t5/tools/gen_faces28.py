#!/usr/bin/env python3
"""The big dial faces of the 2.8" T5.1 gauge, in the round gauge's NOTSTOCK
look: its own draw_face() (../notstock-round/tools/gen_faces.py) at 236 px,
for the pages the big dial shows, plus the DPF icon (A8). Writes
main/faces/faces28.c and faces28.h (the scale geometry for ui_t5.c).

Run from the project root:  python3 tools/gen_faces28.py
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GEN = os.path.join(ROOT, "..", "notstock-round", "tools", "gen_faces.py")
spec = importlib.util.spec_from_file_location("gen_faces", GEN)
gf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gf)

SIZE = 236
OUT = os.path.join(ROOT, "main", "faces")

# the big dial's pages: (name in C, the round gauge's page row, overrides)
BIG = [
    ("boost", "BOOST"),
    ("egt", "EXHAUST"),
    ("rpm", "RPM"),
    ("iat", "INTAKE"),
    ("oil", "OIL"),
    ("clt", "WATER"),
]


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = {p[0]: p for p in gf.PAGES}
    c = ['/* generated by tools/gen_faces28.py, do not edit */',
         '#include "faces28.h"', '']
    h = ['/* generated by tools/gen_faces28.py, do not edit */',
         '#pragma once', '#include "lvgl.h"', '',
         '#define F28_SIZE %d' % SIZE,
         '#define F28_START %d        /* degrees, 0 = 3 o\'clock, clockwise */'
         % gf.START,
         '#define F28_SWEEP %d' % gf.SWEEP,
         '#define F28_ARC_R %d        /* centre line of the groove */'
         % round(gf.GROOVE_R * SIZE / 2),
         '#define F28_GROOVE_W %d' % round(gf.GROOVE_W * SIZE / 2),
         '#define F28_ARC_W %d' % round(gf.ARC_W * SIZE / 2),
         '#define F28_TITLE_Y %d     /* the title over the centre */'
         % round(0.25 * SIZE / 2), '']
    h.append("enum { %s, F28_N };" % ", ".join("F28_" + n.upper() for n, _ in BIG))
    h.append("typedef struct { float lo, hi, warn; const char *unit; } f28_page_t;")
    h.append("extern const f28_page_t F28_PAGE[F28_N];")
    h.append("extern const lv_img_dsc_t *const f28_face[F28_N];")
    tbl = []
    for n, row in BIG:
        p = rows[row]
        img = gf.draw_face(p, SIZE)
        img.save(os.path.join(ROOT, "preview", "face-%s.png" % n))
        gf.emit_rgb(c, "f28_" + n, img)
        h.append("extern const lv_img_dsc_t f28_%s;" % n)
        tbl.append('    { %g, %g, %g, "%s" },' % (p[3], p[4], p[8], p[2]))
    c.append("const f28_page_t F28_PAGE[F28_N] = {")
    c += tbl
    c.append("};")
    c.append("const lv_img_dsc_t *const f28_face[F28_N] = { %s };"
             % ", ".join("&f28_" + n for n, _ in BIG))
    c.append("")
    m = gf.icon_mask("dpf", 64)
    gf.emit_a8(c, "f28_icon_dpf", m)
    h.append("extern const lv_img_dsc_t f28_icon_dpf;      /* 64 px, A8 */")
    with open(os.path.join(OUT, "faces28.c"), "w") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(OUT, "faces28.h"), "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()

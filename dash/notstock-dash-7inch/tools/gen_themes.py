    emit565("hill_bg", img, body)
    gen_dials.emit_rgba("hill_needle", needle, body)
    gen_dials.emit_rgba("hill_hub", hub, body)
    HEADER.append("extern const lv_img_dsc_t hill_needle;")
    HEADER.append("extern const lv_img_dsc_t hill_hub;")
    write("theme_art_hill.c", body)

    HEADER.append("")
    define("HILL_CX", HILL_CX)
    define("HILL_CY", HILL_CY)
    define("HILL_R", HILL_R)
    define("HILL_START", HILL_START)
    define("HILL_SWEEP", HILL_SWEEP)
    define("HILL_TILE_W", HILL_TILE_W)
    define("HILL_TILE_H", HILL_TILE_H)
    define("HILL_SEGS", HILL_SEGS)
    define("HILL_NEEDLE_PIVOT_X", piv[0])
    define("HILL_NEEDLE_PIVOT_Y", piv[1])
    for i, (x, y, left) in enumerate(HILL_TILES):
        define(f"HILL_T{i}_X", x)
        define(f"HILL_T{i}_Y", y)
    # the degree sign is split into its own string literal: "\xC2\xB0C"
    # would read as the hex escape \xB0C and swallow the C
    def c_str(t):
        return '"' + t.replace("\u00b0", '\\xC2\\xB0" "') + '"'
    HEADER.append("static const char *const HILL_UNIT[6] = { " +
                  ", ".join(c_str(t) for t in HILL_UNITS) + " };")



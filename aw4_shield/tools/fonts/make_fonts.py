#!/usr/bin/env python3
"""Generates aw4_fonts.h: 1-bit bitmap fonts for the RP2350 display firmware.
Usage: make_fonts.py <output.h>
Font format (fixed line height, variable width, row-major, each row padded to whole bytes):
  struct AwGlyph { uint32_t offset; uint8_t width; };
  struct AwFont  { const uint8_t *bitmap; const AwGlyph *glyphs; uint8_t first, last, height; };
"""
import sys
from PIL import Image, ImageDraw, ImageFont
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

def make(name, size, chars, out, margin=1):
    f = ImageFont.truetype(TTF, size)
    # line height and vertical offset from the real glyph outlines (nothing gets clipped)
    boxes = [f.getbbox(c) for c in chars if c != " "]
    top = min(b[1] for b in boxes); bottom = max(b[3] for b in boxes)
    line_h = bottom - top + 2 * margin; top_pad = margin - top
    first, last = ord(chars[0]), ord(chars[-1])
    bitmap = []; glyphs = []
    for code in range(first, last + 1):
        ch = chr(code)
        if ch not in chars:
            glyphs.append((len(bitmap), 0)); continue
        adv = int(round(f.getlength(ch))) if ch != " " else max(4, size // 3)
        w = max(adv, 1)
        img = Image.new("1", (w, line_h), 0)
        ImageDraw.Draw(img).text((0, top_pad), ch, font=f, fill=1)
        glyphs.append((len(bitmap), w))
        bpr = (w + 7) // 8
        px = img.load()
        for y in range(line_h):
            for bx in range(bpr):
                v = 0
                for b in range(8):
                    x = bx * 8 + b
                    if x < w and px[x, y]: v |= 0x80 >> b
                bitmap.append(v)
    out.append(f"// {name}: DejaVu Sans Bold {size}px, line height {line_h}, chars '{chars[0]}'..'{chars[-1]}'")
    out.append(f"static const uint8_t {name}_bitmap[] PROGMEM = {{")
    for i in range(0, len(bitmap), 24):
        out.append("  " + ",".join(f"0x{v:02X}" for v in bitmap[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const AwGlyph {name}_glyphs[] PROGMEM = {{")
    for i, (o, w) in enumerate(glyphs):
        out.append(f"  {{{o}, {w}}},  // '{chr(first+i)}'" if chr(first+i) not in "\\'" else f"  {{{o}, {w}}},")
    out.append("};")
    out.append(f"static const AwFont {name} = {{{name}_bitmap, {name}_glyphs, {first}, {last}, {line_h}}};")
    out.append("")
    return len(bitmap)

out = ["// Generated by tools/fonts/make_fonts.py – do not edit.", "#pragma once", "#include <Arduino.h>",
       "struct AwGlyph { uint32_t offset; uint8_t width; };",
       "struct AwFont { const uint8_t *bitmap; const AwGlyph *glyphs; uint8_t first, last, height; };", ""]
ascii = "".join(chr(c) for c in range(32, 127))
n1 = make("fontSmall", 22, ascii, out)
n2 = make("fontBig", 180, "-0123456789", out, margin=2)
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("small bytes", n1, "big bytes", n2)

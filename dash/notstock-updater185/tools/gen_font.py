"""gen_font.py TTF OUT.h: the updater's two text sizes as 8 bit alpha
bitmaps (ASCII and Czech letters), for lcd_text.c. DejaVu Sans Bold."""
import sys
from PIL import ImageFont

TTF, OUT = sys.argv[1], sys.argv[2]
CHARS = [chr(c) for c in range(32, 127)] + list("ÁČĎÉĚÍŇÓŘŠŤÚŮÝŽáčďéěíňóřšťúůýž…")
SIZES = {"big": 34, "small": 24}

lines = ["/* generated by tools/gen_font.py from DejaVu Sans Bold: do not edit */",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct { uint32_t cp; uint32_t off; uint8_t w, h; int8_t x, y; uint8_t adv; } glyph_t;",
         "typedef struct { const glyph_t *g; int n; const uint8_t *bm; int line; } font_t;", ""]
for name, size in SIZES.items():
    f = ImageFont.truetype(TTF, size)
    asc, desc = f.getmetrics()
    bm, gl = bytearray(), []
    for ch in CHARS:
        x0, y0, x1, y1 = f.getbbox(ch)
        m = f.getmask(ch)
        w, h = m.size
        gl.append((ord(ch), len(bm), w, h, x0, y0, round(f.getlength(ch))))
        bm += bytes(m)
    lines.append(f"static const uint8_t {name}_bm[{len(bm)}] = {{")
    for i in range(0, len(bm), 24):
        lines.append("    " + ", ".join(str(b) for b in bm[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const glyph_t {name}_g[{len(gl)}] = {{")
    for g in gl:
        lines.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    lines.append(f"static const font_t font_{name} = {{ {name}_g, {len(gl)}, {name}_bm, {asc + desc} }};")
    lines.append("")
open(OUT, "w").write("\n".join(lines))
